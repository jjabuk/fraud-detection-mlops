"""Collapse a block of columns that carry the same signal.

The IEEE-CIS ``V`` block is 339 anonymized columns generated in families: contiguous
indices sharing a missingness pattern, heavily correlated inside each family. Keeping all
of them costs training time and interpretability without buying accuracy.

Reduction is three steps, and only two of them are mechanical:

1. **Group by missingness.** Columns produced together are absent together, so the null
   count partitions the block. Mechanical — :func:`nan_groups`.
2. **Split each family into correlated sub-groups.** This is judgement, read off
   correlation structure by a human. Taken as given from a pinned file rather than
   re-derived; see ``references/column-groups-v.json``.
3. **Keep one representative per sub-group.** The column with the most distinct values
   carries the most information. Mechanical — :func:`select_representatives`.

Step 2 being somebody's judgement is the reason :func:`audit_partition` exists: a pinned
partition is a claim about the data, and a claim can be checked.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import polars as pl

from fraud_detection.core.feature_contract import Fragment, Rejection

__all__ = [
    "Partition",
    "audit_partition",
    "from_redundancy",
    "load_partition",
    "nan_groups",
    "select_representatives",
]


@dataclass(frozen=True)
class Partition:
    """A pinned split of one or more blocks into correlated sub-groups."""

    blocks: dict[str, tuple[tuple[str, ...], ...]]
    provenance: dict
    uncovered: tuple[str, ...] = ()

    @property
    def groups(self) -> list[tuple[str, ...]]:
        return [g for groups in self.blocks.values() for g in groups]

    @property
    def columns(self) -> list[str]:
        return [c for g in self.groups for c in g]

    def block_of(self, column: str) -> str:
        for name, groups in self.blocks.items():
            if any(column in g for g in groups):
                return name
        raise KeyError(column)

    def with_uncovered(self) -> Partition:
        """Add every uncovered column back as a group of one.

        A column nobody assigned is not a column to drop. Reduction must be a decision
        about each member of the block, and silence is not a decision.
        """
        if not self.uncovered:
            return self
        blocks = dict(self.blocks)
        blocks["unassigned"] = tuple((c,) for c in self.uncovered)
        return Partition(blocks, self.provenance, ())


def load_partition(path: str | Path) -> Partition:
    doc = json.loads(Path(path).read_text())
    return Partition(
        blocks={b["block"]: tuple(tuple(g) for g in b["groups"]) for b in doc["blocks"]},
        provenance=doc.get("provenance", {}),
        uncovered=tuple(doc.get("coverage", {}).get("uncovered", ())),
    )


def nan_groups(df: pl.DataFrame, columns: Sequence[str]) -> dict[int, list[str]]:
    """Partition ``columns`` by their exact null count, largest family first.

    Columns generated by the same upstream step appear and disappear together, so an
    identical null count is strong evidence of shared provenance. This is the one step of
    the reduction that needs no judgement at all.
    """
    counts = df.select(columns).null_count().row(0)
    out: dict[int, list[str]] = {}
    for col, n in zip(columns, counts):
        out.setdefault(int(n), []).append(str(col))
    return dict(sorted(out.items(), key=lambda kv: -len(kv[1])))


def select_representatives(
    df: pl.DataFrame, groups: Sequence[Sequence[str]]
) -> tuple[list[str], list[str]]:
    """Keep the column with the most distinct values from each group; return (kept, dropped).

    Ties break on the order given, so the result is deterministic across runs — which
    matters because this list is committed and compared as a diff.
    """
    kept, dropped = [], []
    cols_set = set(df.columns)
    for group in groups:
        members = [c for c in group if c in cols_set]
        if not members:
            continue
        distinct = {c: int(df.get_column(c).drop_nulls().n_unique()) for c in members}
        winner = max(members, key=lambda c: (distinct[c], -members.index(c)))
        kept.append(winner)
        dropped += [c for c in members if c != winner]
    return kept, dropped


def audit_partition(
    df: pl.DataFrame, partition: Partition, *, sample: int | None = 120_000, seed: int = 0
) -> pl.DataFrame:
    """Does the pinned partition hold on this data?

    For every sub-group, compare the **weakest correlation inside it** against the
    **strongest correlation to a column outside it but inside the same missingness
    family**. A sub-group that means anything should be more tightly bound internally than
    to its neighbours, so ``holds`` is ``min_within > max_outside``.

    Correlations are computed per family, on the rows where that family is populated —
    families share a null pattern, so those rows are complete and the pairwise-complete
    fallback never fires.
    """
    frame = df
    if sample and len(df) > sample:
        frame = df.sample(sample, seed=seed)

    rows = []
    for block, groups in partition.blocks.items():
        members = [c for g in groups for c in g if c in frame.columns]
        if len(members) < 2:
            continue

        present = frame.select(members).filter(~pl.all_horizontal(pl.all().is_null()))
        
        exprs = []
        for i, c1 in enumerate(members):
            for c2 in members[i:]:
                exprs.append(pl.corr(c1, c2).alias(f"{c1}__{c2}"))
                
        if not exprs:
            continue
            
        corr_row = present.select(exprs).row(0)
        
        corr_matrix = np.full((len(members), len(members)), np.nan)
        idx = 0
        for i in range(len(members)):
            for j in range(i, len(members)):
                val = corr_row[idx]
                if val is not None and not np.isnan(val):
                    corr_matrix[i, j] = abs(val)
                    corr_matrix[j, i] = abs(val)
                idx += 1
                
        np.fill_diagonal(corr_matrix, np.nan)
        
        col_to_idx = {c: i for i, c in enumerate(members)}

        for group in groups:
            inside = [c for c in group if c in col_to_idx]
            outside = [c for c in col_to_idx if c not in inside]
            if not inside:
                continue

            def extreme(values: np.ndarray, fn) -> float:
                """NaN when there is nothing to reduce — a constant column correlates
                with nothing, and an empty slice is not a zero."""
                return float(fn(values)) if values.size and not np.isnan(values).all() else float("nan")

            in_idx = [col_to_idx[c] for c in inside]
            out_idx = [col_to_idx[c] for c in outside]
            
            if len(inside) > 1:
                in_corr = corr_matrix[np.ix_(in_idx, in_idx)]
                min_within = extreme(in_corr, np.nanmin)
            else:
                min_within = float("nan")
                
            if out_idx:
                out_corr = corr_matrix[np.ix_(in_idx, out_idx)]
                max_outside = extreme(out_corr, np.nanmax)
            else:
                max_outside = float("nan")

            measurable = not (np.isnan(min_within) or np.isnan(max_outside))
            rows.append({
                "block": block,
                "group": "+".join(group),
                "size": len(group),
                "min_within": None if np.isnan(min_within) else round(min_within, 4),
                "max_outside": None if np.isnan(max_outside) else round(max_outside, 4),
                "holds": bool(min_within > max_outside) if measurable else None,
            })

    return pl.DataFrame(rows)


def from_redundancy(
    dropped: Sequence[str],
    partition: Partition,
    *,
    params: dict | None = None,
    qualification: dict | None = None,
) -> Fragment:
    """Turn a reduction into a contract fragment.

    Every dropped column records the block it belonged to, so a later reader sees that it
    left as a redundant member of a family rather than on its own merits.
    """
    rejections = tuple(
        Rejection(column=c, by="redundancy", value=None, unit=f"block:{partition.block_of(c)}")
        for c in dropped
    )
    return Fragment(
        check="redundancy",
        rejections=rejections,
        params={"method": "nan-group then within-group correlation", **(params or {})},
        qualification=dict(qualification or {}),
        tool="fraud_detection.evaluation.redundancy",
    )
